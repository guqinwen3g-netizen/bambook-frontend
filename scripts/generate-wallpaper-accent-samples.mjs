#!/usr/bin/env node
/**
 * 一次性脚本：扫 public/wallpapers/*，按与运行时一致的算法
 * （把图像降采样到 12×12 求 RGB 算术平均）生成"颜色档案"，
 * 把结果写入 utils/wallpaperAccentSamples.generated.ts。
 *
 * 跑法：
 *   node scripts/generate-wallpaper-accent-samples.mjs
 *
 * 何时跑：新增/替换 public/wallpapers/ 里的内置壁纸时。
 */
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Jimp } from 'jimp';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const REPO_ROOT = path.resolve(__dirname, '..');
const WALLPAPER_DIR = path.join(REPO_ROOT, 'public', 'wallpapers');
const OUTPUT_FILE = path.join(REPO_ROOT, 'utils', 'wallpaperAccentSamples.generated.ts');

// 与运行时 sampleWallpaperAverageColorUncached 完全对齐：12×12 平均色。
const SAMPLE_SIDE = 12;

// SVG 不走 Jimp（Jimp 不支持 SVG）。多数 SVG 壁纸是单色填充，
// 这里用简单正则抓 fill 颜色；抓不到就跳过（运行时仍会自动 fallback）。
const SVG_FILL_REGEX = /<(?:rect|path|circle|polygon|ellipse|stop|svg)[^>]*\s(?:fill|stop-color)\s*=\s*"([^"]+)"/i;
const SVG_STYLE_FILL_REGEX = /(?:fill|stop-color)\s*:\s*([^;\s"]+)/i;

const hexToRgb = (hex) => {
  const m = hex.trim().match(/^#?([0-9a-f]{3}|[0-9a-f]{6})$/i);
  if (!m) return null;
  let v = m[1];
  if (v.length === 3) v = v.split('').map(c => c + c).join('');
  return {
    r: parseInt(v.slice(0, 2), 16),
    g: parseInt(v.slice(2, 4), 16),
    b: parseInt(v.slice(4, 6), 16),
  };
};

const NAMED_COLORS = {
  black: { r: 0, g: 0, b: 0 },
  white: { r: 255, g: 255, b: 255 },
  red: { r: 255, g: 0, b: 0 },
  green: { r: 0, g: 128, b: 0 },
  blue: { r: 0, g: 0, b: 255 },
};

const parseSvgFill = async (filePath) => {
  const text = await fs.readFile(filePath, 'utf8');
  const styleMatch = text.match(SVG_STYLE_FILL_REGEX);
  const attrMatch = text.match(SVG_FILL_REGEX);
  const raw = (styleMatch?.[1] || attrMatch?.[1] || '').trim();
  if (!raw) return null;
  if (raw.startsWith('#')) return hexToRgb(raw);
  if (raw.startsWith('rgb')) {
    const nums = raw.match(/\d+(\.\d+)?/g);
    if (nums && nums.length >= 3) {
      return { r: Number(nums[0]), g: Number(nums[1]), b: Number(nums[2]) };
    }
  }
  if (NAMED_COLORS[raw.toLowerCase()]) return NAMED_COLORS[raw.toLowerCase()];
  return null;
};

const sampleRaster = async (filePath) => {
  const image = await Jimp.read(filePath);
  image.resize({ w: SAMPLE_SIDE, h: SAMPLE_SIDE });
  let r = 0, g = 0, b = 0, count = 0;
  // Jimp v1 scan iterates over every pixel.
  image.scan(0, 0, image.bitmap.width, image.bitmap.height, function scanPixel(_x, _y, idx) {
    r += this.bitmap.data[idx];
    g += this.bitmap.data[idx + 1];
    b += this.bitmap.data[idx + 2];
    count += 1;
  });
  if (!count) return null;
  return { r: r / count, g: g / count, b: b / count };
};

const sampleFile = async (filePath) => {
  const ext = path.extname(filePath).toLowerCase();
  if (ext === '.svg') return parseSvgFill(filePath);
  if (['.jpg', '.jpeg', '.png', '.webp', '.bmp', '.tiff', '.gif'].includes(ext)) {
    return sampleRaster(filePath);
  }
  return null;
};

const roundTo = (n, digits = 4) => Number(n.toFixed(digits));

const main = async () => {
  const entries = (await fs.readdir(WALLPAPER_DIR)).sort();
  /** @type {Record<string, {r:number;g:number;b:number}>} */
  const result = {};
  const skipped = [];
  for (const entry of entries) {
    const filePath = path.join(WALLPAPER_DIR, entry);
    const stat = await fs.stat(filePath);
    if (!stat.isFile()) continue;
    try {
      const sample = await sampleFile(filePath);
      if (!sample) {
        skipped.push(entry);
        continue;
      }
      result[`/wallpapers/${entry}`] = {
        r: roundTo(sample.r),
        g: roundTo(sample.g),
        b: roundTo(sample.b),
      };
      console.log(`✓ ${entry} -> rgb(${sample.r.toFixed(1)}, ${sample.g.toFixed(1)}, ${sample.b.toFixed(1)})`);
    } catch (err) {
      skipped.push(`${entry} (${err.message})`);
    }
  }
  if (skipped.length) {
    console.warn(`\n[skipped ${skipped.length}]`);
    for (const item of skipped) console.warn(`  - ${item}`);
  }

  const header = `// AUTO-GENERATED by scripts/generate-wallpaper-accent-samples.mjs
// Do NOT edit by hand. Run \`node scripts/generate-wallpaper-accent-samples.mjs\`
// whenever wallpapers under public/wallpapers/ change.

import type { WallpaperAccentRGB } from './wallpaperAccent';

export const BUILTIN_WALLPAPER_ACCENT_SAMPLES: Readonly<Record<string, WallpaperAccentRGB>> = `;
  const body = JSON.stringify(result, null, 2) + ' as const;\n';
  await fs.writeFile(OUTPUT_FILE, header + body, 'utf8');
  console.log(`\nWrote ${Object.keys(result).length} samples to ${path.relative(REPO_ROOT, OUTPUT_FILE)}`);
};

main().catch(err => {
  console.error(err);
  process.exit(1);
});
