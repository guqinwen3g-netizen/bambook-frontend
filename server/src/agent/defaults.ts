  llmRepairRetries: 1,
  /** 构建上下文时取最近多少轮对话历史（0=不含历史）。 */
  historyWindowSize: 8,
  /** 单个工具输出在 observation 中的字符上限（超出截断）。 */
  observationCharLimit: 6000,
  /** 整个 scratchpad observation 块的总字符预算（超出时从最早 step 压缩）。 */
